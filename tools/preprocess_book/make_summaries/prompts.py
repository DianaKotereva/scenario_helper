"""
Промпт для создания суммаризаций глав книги.

Модуль содержит класс SummarizationPrompt для генерации
повествовательных суммаризаций текста глав.
"""

from typing import Dict, Any
from src.llm_core.llm_prompt_base import LLMBase


system_prompt_summarization = """Проанализируй представленный текст главы/сцены книги и создай детальную, последовательную повествовательную суммаризацию для последующего использования в RAG-системе.

**Твои входные данные:** 
1. Текст - текст главы, который ты должен суммаризовать. 

**Структурирование нарратива:**  
   — Воспроизведи логическую последовательность событий, сохранив причинно-следственные связи.  
   — Выдели ключевые повороты сюжета, изменения в мотивациях персонажей и значимые диалоги.  
   — Отметь скрытые эмоции, подтексты или символические элементы, если они влияют на развитие истории.   
   — Сохрани атмосферу и тон оригинала (например, «мрачный», «ироничный», «напряженный»).  

**Требования к формату:**  
— Суммаризация должна читаться как связный микрорассказ (1-2 абзаца), а не как список пунктов.  
— Избегай интерпретаций и домыслов — только явная информация из текста.  

Верни только суммаризацию сцены, без каких-либо дополнительных примечаний."""


class SummarizationPrompt(LLMBase):
    """
    Класс для создания суммаризаций глав книги.
    
    Использует LLM для генерации повествовательных суммаризаций
    на основе текста глав, сохраняя структуру и стиль оригинала.
    """
    
    def __init__(self, llm, parser=None):
        """
        Инициализирует SummarizationPrompt.
        
        Args:
            llm: Инициализированная языковая модель
            parser: Парсер для вывода (опционально, для суммаризации не требуется)
        """
        super().__init__(
            llm=llm,
            system_prompt=system_prompt_summarization,
            parser=parser,
            parse_json=False
        )
    
    def make_user_prompt(self, text: str) -> Dict[str, Any]:
        """
        Форматирует пользовательский промпт для суммаризации.
        
        Args:
            text: Текст главы для суммаризации
            
        Returns:
            Словарь с сообщениями для LLM в формате {"messages": [("user", prompt)]}
            
        Raises:
            ValueError: Если текст пустой
        """
        if not text or not isinstance(text, str):
            raise ValueError("text must be a non-empty string")
        
        user_prompt = f"Текст: {text}"
        return {"messages": [("user", user_prompt)]}
